#!/usr/bin/env node
/**
 * Sync guide-flow JSON + i18n bundle into consumer-app and provider-app (ai-guide-1.9.1).
 * Writes offline manifest stamped with app version + corpus revision (ai-guide-1.9.12).
 * Source of truth: backend/src/modules/ai/guide/guide-flows + dashboard-guide-corpus-i18n.snapshot.json
 */
import { createHash } from 'node:crypto';
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const BACKEND_GUIDE = join(ROOT, 'backend/src/modules/ai/guide');
const FLOWS_ROOT = join(BACKEND_GUIDE, 'guide-flows');
const SNAPSHOT = join(BACKEND_GUIDE, 'dashboard-guide-corpus-i18n.snapshot.json');

const APP_TARGETS = [
  {
    app: 'consumer-app',
    surface: 'customer',
    playbooksDir: 'customer',
  },
  {
    app: 'provider-app',
    surface: 'provider',
    playbooksDir: 'provider',
  },
];

function readJson(path) {
  return JSON.parse(readFileSync(path, 'utf8'));
}

function copyDir(src, dest) {
  mkdirSync(dest, { recursive: true });
  for (const name of readdirSync(src)) {
    const from = join(src, name);
    const to = join(dest, name);
    cpSync(from, to, { recursive: true });
  }
}

function extractGuideFlowsI18n(snapshot) {
  const out = {};
  for (const locale of ['en', 'hy', 'ru']) {
    const flows = snapshot[locale]?.guide?.flows;
    if (!flows) {
      throw new Error(`missing ${locale}.guide.flows in ${SNAPSHOT}`);
    }
    out[locale] = { guide: { flows } };
  }
  return out;
}

function listJsonPlaybooks(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((name) => name.endsWith('.json'))
    .sort();
}

function listJsonFilesRecursive(dir) {
  if (!existsSync(dir)) return [];
  const out = [];
  for (const name of readdirSync(dir).sort()) {
    const full = join(dir, name);
    const stat = statSync(full);
    if (stat.isDirectory()) {
      out.push(...listJsonFilesRecursive(full));
    } else if (name.endsWith('.json')) {
      out.push(full);
    }
  }
  return out;
}

function computeCorpusRevision() {
  const hash = createHash('sha256');
  for (const file of listJsonFilesRecursive(FLOWS_ROOT)) {
    hash.update(relative(ROOT, file));
    hash.update('\0');
    hash.update(readFileSync(file));
    hash.update('\0');
  }
  hash.update(readFileSync(SNAPSHOT));
  return hash.digest('hex').slice(0, 16);
}

function readAppVersion(appRoot) {
  const pkg = readJson(join(appRoot, 'package.json'));
  const version = pkg.version?.trim();
  if (!version) {
    throw new Error(`missing version in ${join(appRoot, 'package.json')}`);
  }
  return version;
}

function buildOfflineManifest({ surface, appVersion, corpusRevision, playbookCount, overlayCount }) {
  return {
    surface,
    appVersion,
    corpusRevision,
    syncedAt: new Date().toISOString(),
    playbookCount,
    overlayCount,
    locales: ['en', 'hy', 'ru'],
  };
}

function generateBundleTs({ surface, playbooksDir, assetsRel, playbookFiles, overlayFiles }) {
  const playbookImports = playbookFiles
    .map(
      (file, index) =>
        `import playbook_${index} from '${assetsRel}/guide-flows/${playbooksDir}/${file}';`,
    )
    .join('\n');

  const overlayImports = overlayFiles
    .map(
      (file, index) =>
        `import overlay_${index} from '${assetsRel}/guide-flows/overlays/${file}';`,
    )
    .join('\n');

  const playbookRefs = playbookFiles.map((_, index) => `playbook_${index}`).join(', ');
  const overlayRefs = overlayFiles.map((_, index) => `overlay_${index}`).join(', ');

  return `/** Generated by scripts/sync-mobile-guide-flows.mjs — do not edit. */
import type {
  GuideFlowOverlayBundle,
  GuideFlowPlaybookDef,
  MobileGuideBundle,
  MobileGuideOfflineManifest,
} from '@mobile-guide/mobile-guide.types.ts';
${playbookImports}
${overlayImports}
import guideFlowsI18n from '${assetsRel}/guide-flows-i18n.json';
import guideFlowsManifest from '${assetsRel}/guide-flows-manifest.json';

export const MOBILE_GUIDE_OFFLINE_MANIFEST = guideFlowsManifest as MobileGuideOfflineManifest;

export const MOBILE_GUIDE_BUNDLE: MobileGuideBundle = {
  surface: '${surface}',
  playbooks: [${playbookRefs}] as GuideFlowPlaybookDef[],
  overlays: [${overlayRefs}] as GuideFlowOverlayBundle[],
  i18n: guideFlowsI18n as MobileGuideBundle['i18n'],
};
`;
}

function syncApp(target, corpusRevision) {
  const appRoot = join(ROOT, target.app);
  const assetsRoot = join(appRoot, 'src/assets');
  const flowsDest = join(assetsRoot, 'guide-flows');
  const playbooksSrc = join(FLOWS_ROOT, target.playbooksDir);
  const overlaysSrc = join(FLOWS_ROOT, 'overlays');

  rmSync(flowsDest, { recursive: true, force: true });
  mkdirSync(join(flowsDest, target.playbooksDir), { recursive: true });
  copyDir(playbooksSrc, join(flowsDest, target.playbooksDir));
  copyDir(overlaysSrc, join(flowsDest, 'overlays'));

  const snapshot = readJson(SNAPSHOT);
  const i18n = extractGuideFlowsI18n(snapshot);
  writeFileSync(
    join(assetsRoot, 'guide-flows-i18n.json'),
    `${JSON.stringify(i18n, null, 2)}\n`,
  );

  const playbookFiles = listJsonPlaybooks(playbooksSrc);
  const overlayFiles = listJsonPlaybooks(overlaysSrc);
  const appVersion = readAppVersion(appRoot);
  const manifest = buildOfflineManifest({
    surface: target.surface,
    appVersion,
    corpusRevision,
    playbookCount: playbookFiles.length,
    overlayCount: overlayFiles.length,
  });
  writeFileSync(
    join(assetsRoot, 'guide-flows-manifest.json'),
    `${JSON.stringify(manifest, null, 2)}\n`,
  );

  const bundlePath = join(appRoot, 'src/lib/mobile-guide/mobile-guide.bundle.ts');
  mkdirSync(dirname(bundlePath), { recursive: true });
  writeFileSync(
    bundlePath,
    generateBundleTs({
      surface: target.surface,
      playbooksDir: target.playbooksDir,
      assetsRel: '../../assets',
      playbookFiles,
      overlayFiles,
    }),
  );

  console.log(
    `[sync-mobile-guide-flows] ${target.app}: ${playbookFiles.length} playbooks, ${overlayFiles.length} overlays, v${appVersion}, corpus ${corpusRevision}`,
  );
}

function main() {
  if (!existsSync(FLOWS_ROOT)) {
    throw new Error(`missing guide-flows: ${FLOWS_ROOT}`);
  }
  if (!existsSync(SNAPSHOT)) {
    throw new Error(`missing snapshot: ${SNAPSHOT}`);
  }

  const corpusRevision = computeCorpusRevision();
  for (const target of APP_TARGETS) {
    syncApp(target, corpusRevision);
  }

  console.log('[sync-mobile-guide-flows] done');
}

main();
